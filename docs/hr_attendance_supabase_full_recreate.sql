-- =========================================================

CREATE OR REPLACE FUNCTION public.process_qr_attendance(
    p_qr_code_value TEXT,
    p_log_type TEXT,
    p_device_id TEXT DEFAULT NULL,
    p_location TEXT DEFAULT NULL,
    p_latitude NUMERIC DEFAULT NULL,
    p_longitude NUMERIC DEFAULT NULL,
    p_ip_address INET DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_app_user_id BIGINT;
    v_employee_id BIGINT;
    v_now TIMESTAMPTZ := now();
    v_today DATE := (now() AT TIME ZONE 'Asia/Phnom_Penh')::date;
    v_local_now TIMESTAMP := (now() AT TIME ZONE 'Asia/Phnom_Penh');
    v_qr_location_id BIGINT;
    v_record_id BIGINT;
    v_log_id BIGINT;
    v_check_in TIMESTAMPTZ;
    v_check_out TIMESTAMPTZ;
    v_start_time TIME;
    v_late_minutes INT := 0;
    v_message TEXT;
BEGIN
    IF p_log_type NOT IN ('check_in', 'check_out', 'break_in', 'break_out') THEN
        RAISE EXCEPTION 'Invalid log type: %', p_log_type;
    END IF;

    v_app_user_id := public.current_app_user_id();
    v_employee_id := public.current_employee_id();

    IF v_app_user_id IS NULL OR v_employee_id IS NULL THEN
        RAISE EXCEPTION 'No active app user / employee profile is linked to this Supabase Auth user.';
    END IF;

    SELECT id INTO v_qr_location_id
    FROM public.qr_locations
    WHERE qr_code_value = p_qr_code_value
      AND is_active = TRUE
    LIMIT 1;

    IF v_qr_location_id IS NULL THEN
        RAISE EXCEPTION 'Invalid or inactive QR code.';
    END IF;

    SELECT ws.start_time INTO v_start_time
    FROM public.employee_schedules es
    JOIN public.working_schedules ws ON ws.id = es.schedule_id
    WHERE es.employee_id = v_employee_id
      AND es.effective_from <= v_today
      AND (es.effective_to IS NULL OR es.effective_to >= v_today)
      AND ws.is_active = TRUE
    ORDER BY es.effective_from DESC
    LIMIT 1;

    IF v_start_time IS NOT NULL THEN
        v_late_minutes := GREATEST(FLOOR(EXTRACT(EPOCH FROM (v_local_now - (v_today + v_start_time))) / 60)::INT, 0);
    END IF;

    INSERT INTO public.attendance_records (
        employee_id,
        attendance_date,
        status,
        created_by,
        updated_by
    )
    VALUES (
        v_employee_id,
        v_today,
        'present',
        v_app_user_id,
        v_app_user_id
    )
    ON CONFLICT (employee_id, attendance_date) DO NOTHING;

    SELECT id, check_in, check_out
    INTO v_record_id, v_check_in, v_check_out
    FROM public.attendance_records
    WHERE employee_id = v_employee_id
      AND attendance_date = v_today;

    IF p_log_type = 'check_in' THEN
        IF v_check_in IS NULL THEN
            UPDATE public.attendance_records
            SET check_in = v_now,
                late_minutes = v_late_minutes,
                status = CASE WHEN v_late_minutes > 0 THEN 'late' ELSE 'present' END,
                updated_by = v_app_user_id
            WHERE id = v_record_id
            RETURNING check_in, check_out INTO v_check_in, v_check_out;
            v_message := 'Check-in successful.';
        ELSE
            v_message := 'Check-in already exists. New scan log was saved, but check-in was not overwritten.';
        END IF;
    ELSIF p_log_type = 'check_out' THEN
        IF v_check_in IS NULL THEN
            UPDATE public.attendance_records
            SET check_out = v_now,
                status = 'missing_checkin',
                updated_by = v_app_user_id
            WHERE id = v_record_id
            RETURNING check_in, check_out INTO v_check_in, v_check_out;
            v_message := 'Checkout saved, but check-in is missing.';
        ELSE
            UPDATE public.attendance_records
            SET check_out = v_now,
                worked_hours = ROUND((EXTRACT(EPOCH FROM (v_now - check_in)) / 3600.0)::NUMERIC, 2),
                status = CASE WHEN status = 'late' THEN 'late' ELSE 'present' END,
                updated_by = v_app_user_id
            WHERE id = v_record_id
            RETURNING check_in, check_out INTO v_check_in, v_check_out;
            v_message := 'Checkout successful.';
        END IF;
    ELSIF p_log_type IN ('break_in', 'break_out') THEN
        v_message := 'Break scan log saved.';
    END IF;

    INSERT INTO public.attendance_logs (
        employee_id,
        attendance_record_id,
        log_type,
        attendance_type,
        log_time,
        qr_code_value,
        device_id,
        location,
        latitude,
        longitude,
        ip_address
    )
    VALUES (
        v_employee_id,
        v_record_id,
        p_log_type,
        'qr_code',
        v_now,
        p_qr_code_value,
        p_device_id,
        p_location,
        p_latitude,
        p_longitude,
        p_ip_address::TEXT
    )
    RETURNING id INTO v_log_id;

    RETURN jsonb_build_object(
        'success', TRUE,
        'message', v_message,
        'attendance_record_id', v_record_id,
        'log_id', v_log_id,
        'employee_id', v_employee_id,
        'attendance_date', v_today,
        'check_in', v_check_in,
        'check_out', v_check_out
    );
END;
