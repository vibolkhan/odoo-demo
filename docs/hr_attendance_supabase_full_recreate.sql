-- 4. Security helper functions for RLS
-- =========================================================

CREATE OR REPLACE FUNCTION public.current_app_user_id()
RETURNS BIGINT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT au.id
    FROM public.app_users au
    WHERE au.auth_user_id = auth.uid()
      AND au.is_active = TRUE
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.current_employee_id()
RETURNS BIGINT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT au.employee_id
    FROM public.app_users au
    WHERE au.auth_user_id = auth.uid()
      AND au.is_active = TRUE
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.current_role_name()
RETURNS TEXT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT r.name
    FROM public.app_users au
    JOIN public.roles r ON r.id = au.role_id
    WHERE au.auth_user_id = auth.uid()
      AND au.is_active = TRUE
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.is_admin_or_hr()
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT COALESCE(public.current_role_name() IN ('Admin', 'HR Manager'), FALSE);
$$;

CREATE OR REPLACE FUNCTION public.is_manager()
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT COALESCE(public.current_role_name() = 'Manager', FALSE);
$$;

CREATE OR REPLACE FUNCTION public.can_view_employee(target_employee_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT COALESCE(
        public.is_admin_or_hr()
        OR target_employee_id = public.current_employee_id()
        OR EXISTS (
            SELECT 1
            FROM public.employees e
            WHERE e.id = target_employee_id
              AND e.manager_id = public.current_employee_id()
        ),
        FALSE
    );
$$;

CREATE OR REPLACE FUNCTION public.can_manage_employee_data(target_employee_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT COALESCE(
        public.is_admin_or_hr()
        OR EXISTS (
            SELECT 1
            FROM public.employees e
            WHERE e.id = target_employee_id
              AND e.manager_id = public.current_employee_id()
        ),
        FALSE
    );
$$;

