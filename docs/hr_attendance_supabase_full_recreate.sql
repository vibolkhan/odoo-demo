CREATE VIEW public.v_attendance_history
WITH (security_invoker = true)
AS
SELECT
    ar.id AS attendance_record_id,
    ar.attendance_date,
    e.id AS employee_id,
    e.employee_code,
    concat(e.first_name, ' ', e.last_name) AS employee_name,
    d.name AS department_name,
    p.title AS position_title,
    ar.check_in,
    ar.check_out,
    ar.worked_hours,
    ar.late_minutes,
    ar.early_leave_minutes,
    ar.overtime_minutes,
    ar.status,
    ar.note
FROM public.attendance_records ar
JOIN public.employees e ON e.id = ar.employee_id
LEFT JOIN public.departments d ON d.id = e.department_id
LEFT JOIN public.positions p ON p.id = e.position_id;

CREATE VIEW public.v_employee_attendance_history
WITH (security_invoker = true)
AS
SELECT * FROM public.v_attendance_history;

CREATE VIEW public.v_today_attendance_summary
WITH (security_invoker = true)
AS
SELECT
    (now() AT TIME ZONE 'Asia/Phnom_Penh')::date AS attendance_date,
    COUNT(e.id) FILTER (WHERE e.status = 'active') AS total_employees,
    COUNT(ar.id) FILTER (WHERE ar.status IN ('present', 'late', 'early_leave', 'missing_checkout')) AS present_today,
    COUNT(ar.id) FILTER (WHERE ar.status = 'late' OR ar.late_minutes > 0) AS late_today,
    COUNT(e.id) FILTER (WHERE e.status = 'active' AND ar.id IS NULL) AS absent_today,
    COUNT(ar.id) FILTER (WHERE ar.check_in IS NOT NULL AND ar.check_out IS NULL) AS missing_checkout,
    COUNT(ar.id) FILTER (WHERE ar.status = 'on_leave') AS on_leave_today
FROM public.employees e
LEFT JOIN public.attendance_records ar
    ON ar.employee_id = e.id
   AND ar.attendance_date = (now() AT TIME ZONE 'Asia/Phnom_Penh')::date;

CREATE VIEW public.v_pending_requests_summary
WITH (security_invoker = true)
AS
SELECT
    (SELECT COUNT(*) FROM public.leave_requests WHERE status = 'pending') AS pending_leave,
    (SELECT COUNT(*) FROM public.overtime_requests WHERE status = 'pending') AS pending_overtime,
    (SELECT COUNT(*) FROM public.attendance_corrections WHERE status = 'pending') AS pending_attendance_corrections;

